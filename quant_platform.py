strategy_dates = []

top_n = 3

for i in range(12, len(monthly_returns)-1):

    signal_date = monthly_returns.index[i]

    next_date = monthly_returns.index[i+1]

    factor_signal = rolling_momentum.loc[signal_date]

    ranked = factor_signal.sort_values(
        ascending=False
    )

    long_stocks = ranked.head(top_n).index

    short_stocks = ranked.tail(top_n).index

    next_returns = monthly_returns.loc[next_date]

    long_return = next_returns[long_stocks].mean()

    short_return = next_returns[short_stocks].mean()

    portfolio_return = long_return - short_return

    strategy_returns.append(portfolio_return)

    strategy_dates.append(next_date)

rolling_strategy = pd.Series(
    strategy_returns,
    index=strategy_dates
)

rolling_cumulative = (
    1 + rolling_strategy
).cumprod()

rolling_cumulative.tail()

