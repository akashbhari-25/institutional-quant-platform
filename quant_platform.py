"""# Phase 4 — Institutional Rolling Rebalance Backtest Engine"""

monthly_prices = prices.resample("M").last()

monthly_returns = monthly_prices.pct_change().dropna()

monthly_prices.head()

rolling_momentum = monthly_prices.pct_change(12)

